// Regression test for Lesson 836 (2026-09-09, David): every
// `#[tauri::command]` function MUST have a matching `allow-*` permission
// in BOTH `default.toml` AND `capabilities/main.json` (or whichever
// capability scope is intended).
//
// Symptom of drift: clicking the Workflows tile on rc55.23 navigated
// to a page showing "Could not load the workflow library. Try
// restarting MiracleClaw." Underneath, `prose_examples` was being
// silently rejected by Tauri's runtime ACL — the invoke error was
// "Command prose_examples not allowed by ACL" — and our friendly
// catch block swallowed the cause behind a generic message.
//
// This test would have caught the rc55.22 → rc55.23 regression in
// <1s without ever running the app. It scans every `#[tauri::command]`
// in the source tree, derives the expected `allow-*` identifier
// (snake_case → kebab-case), and asserts the identifier appears in
// either `default.toml` (for main-window invocation) or `bridge.json`
// (for the http://127.0.0.1:28789 chat bridge).
//
// Companion test: `acl_sync_smoke.rs` verifies the OTHER direction
// (every `allow-*` in `default.toml` is also in `main.json`). Together
// these two tests form a complete symmetry check:
//   - forward: every command has an allow  (THIS FILE)
//   - reverse: every allow has a command   (acl_sync_smoke.rs)
//
// Authoring rule (Lesson 219 / 755 / 836): when you add a new
// `#[tauri::command] fn foo_bar` in any *.rs file under src/, you
// must ALSO add three lines:
//   1. `allow-foo-bar` in src-tauri/permissions/default.toml
//   2. `allow-foo-bar` in src-tauri/capabilities/main.json
//   3. `[[permission]] identifier = "allow-foo-bar"` in
//      src-tauri/permissions/autogenerated/commands/app_commands.toml
//      (this file is regenerated by `tauri_build::build()` but is
//      load-bearing if the autogeneration step is skipped — Lesson 219
//      sccache trap).
// Without all three, JS `invoke("foo_bar", ...)` will be rejected at
// runtime with "Command foo_bar not allowed by ACL".

use std::collections::HashSet;
use std::fs;
use std::path::{Path, PathBuf};

/// Derive the expected `allow-*` identifier from a Tauri command name.
/// `mc_secret_set` → `mc-secret-set`, `prose_examples` → `prose-examples`.
fn command_to_allow_ident(cmd: &str) -> String {
    cmd.replace('_', "-")
}

/// Walk every *.rs file under `src-tauri/src/` and return the set of
/// `#[tauri::command]` function names found. We use a regex-free,
/// state-machine parser so the test has no extra dev-dependencies.
fn discover_tauri_commands(src_root: &Path) -> Vec<String> {
    let mut out = Vec::new();
    fn walk(p: &Path, out: &mut Vec<String>) {
        if let Ok(rd) = fs::read_dir(p) {
            for entry in rd.flatten() {
                let path = entry.path();
                if path.is_dir() {
                    walk(&path, out);
                } else if path.extension().map(|e| e == "rs").unwrap_or(false) {
                    if let Ok(s) = fs::read_to_string(&path) {
                        parse_commands_in(&s, out);
                    }
                }
            }
        }
    }
    walk(src_root, &mut out);
    out.sort();
    out.dedup();
    out
}

/// Parse a single source file for `#[tauri::command]` followed by a
/// function definition. We look for the literal attribute, then scan
/// forward through whitespace + attributes + comments until we find
/// `fn <name>`.
///
/// Heuristic that covers our codebase:
///   - `pub fn foo_bar(...)`       → "foo_bar"
///   - `pub(crate) fn foo_bar(...)` → "foo_bar"
///   - multi-line attributes between `#[tauri::command]` and `fn` are
///     skipped (we just `getline` until we see `fn `)
///
/// False-positive traps (Lesson 836 anti-regression) this parser avoids:
///
/// 1. **Doc comments mentioning `#[tauri::command]`**: Comment lines like
///    `//   1. lib.rs's mc_secret_set is a #[tauri::command] which means...`
///    contain the substring but are NOT attribute lines. We mitigate by
///    requiring the line to START with `#[tauri::command]` (allowing only
///    leading whitespace). Comment lines never start with `#[`.
///
/// 2. **Glob paths in comments/captures**: Lines like
///    `/// Populated at startup by scanning \`<app_data>/modules/*/installer.json\``
///    contain `/*` (a glob), NOT a block-comment opener. Naive parsers
///    that detect block comments by searching for `/*` will get stuck in
///    "block comment mode" forever because the `/*` is never closed with
///    a same-line `*/`. Our codebase has NO real `/* ... */` block
///    comments (only `///` and `//!` doc comments and `//` line comments),
///    so we deliberately skip block-comment tracking.
///
/// 3. **Helper functions after `#[tauri::command]` functions**: Some
///    files (e.g., secrets_friendly.rs) have a `#[tauri::command]`
///    function whose body references helper functions defined LATER in
///    the file. We walk forward and capture the FIRST `fn ` we see,
///    which is correct for the `[#[tauri::command]] → fn` adjacency
///    pattern. If the test ever needs to capture helper functions too,
///    we'll need a more robust parser (saving that for when it bites).
fn parse_commands_in(source: &str, out: &mut Vec<String>) {
    let mut lines = source.lines().peekable();
    let mut line_idx: usize = 0;
    while let Some(line) = lines.next() {
        line_idx += 1;
        let trimmed = line.trim_start();

        // Match ONLY a real attribute line, not a comment that mentions it.
        if trimmed != "#[tauri::command]" {
            continue;
        }        // Found a #[tauri::command] attribute. Walk forward until `fn <name>`.
        for next in lines.by_ref() {
            let trimmed = next.trim();
            if trimmed.is_empty() || trimmed.starts_with("//") {
                continue;
            }
            if trimmed.starts_with('#') {
                // another attribute on the same fn — keep scanning
                continue;
            }
            // Look for `fn <ident>` in this line
            if let Some(idx) = trimmed.find("fn ") {
                let after = &trimmed[idx + 3..];
                // Take characters until we hit `<`, `(`, whitespace, or `:`.
                let name: String = after
                    .chars()
                    .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                    .collect();
                if !name.is_empty() && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_') {
                    out.push(name);
                }
                break;
            }
            // If this line has nothing useful, keep scanning forward.
        }
    }
}

/// Read every `"allow-*"` identifier from a JSON capability file.
/// We use a simple string scan (the format is well-controlled:
/// `"allow-..."` appears only inside the permissions array as strings).
fn allow_idents_in_json(path: &Path) -> HashSet<String> {
    let s = match fs::read_to_string(path) {
        Ok(s) => s,
        Err(_) => return HashSet::new(),
    };
    let mut out = HashSet::new();
    let mut rest = s.as_str();
    while let Some(idx) = rest.find("\"allow-") {
        rest = &rest[idx + 1..];
        if let Some(end) = rest.find('"') {
            out.insert(rest[..end].to_string());
            rest = &rest[end + 1..];
        } else {
            break;
        }
    }
    out
}

/// Read every `"allow-*"` identifier from default.toml.
fn allow_idents_in_default_toml(path: &Path) -> HashSet<String> {
    let s = match fs::read_to_string(path) {
        Ok(s) => s,
        Err(_) => return HashSet::new(),
    };
    let mut out = HashSet::new();
    let mut rest = s.as_str();
    while let Some(idx) = rest.find("\"allow-") {
        rest = &rest[idx + 1..];
        if let Some(end) = rest.find('"') {
            out.insert(rest[..end].to_string());
            rest = &rest[end + 1..];
        } else {
            break;
        }
    }
    out
}

fn project_root() -> PathBuf {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    manifest_dir.parent().unwrap().to_path_buf()
}

/// Some commands are intentionally scoped to capabilities OTHER than
/// main.json (e.g. `bridge.json` for the chat bridge at
/// http://127.0.0.1:28789). Those commands should NOT need to be in
/// main.json — but they still MUST be in default.toml (default.toml is
/// the permission DEFINITIONS manifest, not the runtime ACL).
///
/// Add an entry here for any command that lives outside main.json.
/// Format: "snake_case_command" — explanation is in the test failure
/// message.
const COMMANDS_OUTSIDE_MAIN: &[&str] = &[
    // bridge.json commands (chat bridge at 127.0.0.1:28789 origin)
    // The bridge origin needs these specifically because the chat UI
    // there CANNOT use the local-origin (tauri://localhost) main.json
    // permission set.
    "openclaw_back_to_dashboard",
    "mc_module_install_url",
];

/// A command may be intentionally non-ACL-gated if it has special
/// handling (e.g. called from a Tauri setup hook rather than from JS).
/// This is the "test-known-skip" list — every entry must have a brief
/// comment explaining why it's skipped.
const COMMANDS_INTENTIONALLY_SKIPPED: &[(&str, &str)] = &[
    // (none as of Lesson 836 — every command should be ACL-gated)
];

#[test]
fn every_tauri_command_has_allow_in_default_toml() {
    let root = project_root();
    let src_root = root.join("src-tauri/src");
    let default_toml = root.join("src-tauri/permissions/default.toml");

    let commands = discover_tauri_commands(&src_root);
    let allow_idents = allow_idents_in_default_toml(&default_toml);

    let skipped: HashSet<&str> = COMMANDS_INTENTIONALLY_SKIPPED
        .iter()
        .map(|(n, _)| *n)
        .collect();

    let mut missing = Vec::new();
    for cmd in &commands {
        if skipped.contains(cmd.as_str()) {
            continue;
        }
        let expected = format!("allow-{}", command_to_allow_ident(cmd));
        if !allow_idents.contains(&expected) {
            missing.push((cmd.clone(), expected));
        }
    }

    assert!(
        missing.is_empty(),
        "\n\n❌ Tauri command ACL drift detected (Lesson 836, 2026-09-09)!\n\
         These `#[tauri::command]` functions have NO `{}` entry in \
         src-tauri/permissions/default.toml:\n  - {}\n\n\
         JS invocations will fail at runtime with \
         'Command <name> not allowed by ACL'. Symptom in the UI: \
         generic 'Could not load ...' or 'Try restarting MiracleClaw' \
         messages that swallow the real cause.\n\n\
         Fix:\n  1. Add `\"allow-<name>\"` to default.toml's permissions array\n\
         2. Add `\"allow-<name>\"` to capabilities/main.json's permissions array\n\
         3. Add `[[permission]] identifier = \"allow-<name>\"` block to \
         permissions/autogenerated/commands/app_commands.toml\n\
         4. If the command is scoped to capabilities/bridge.json instead of \
         main.json, add it to COMMANDS_OUTSIDE_MAIN in this test.\n\n\
         Found {} commands total, {} allow-* in default.toml.\n",
        "{allow-X}",
        missing
            .iter()
            .map(|(c, a)| format!("fn {} → missing {}", c, a))
            .collect::<Vec<_>>()
            .join("\n  - "),
        commands.len(),
        allow_idents.len()
    );

    println!(
        "\n✓ all {} #[tauri::command] functions have an allow-* entry in default.toml",
        commands.len()
    );
}

#[test]
fn every_tauri_command_has_allow_in_main_json_or_bridge_json() {
    let root = project_root();
    let src_root = root.join("src-tauri/src");
    let main_json = root.join("src-tauri/capabilities/main.json");
    let bridge_json = root.join("src-tauri/capabilities/bridge.json");

    let commands = discover_tauri_commands(&src_root);
    let main_allows = allow_idents_in_json(&main_json);
    let bridge_allows = allow_idents_in_json(&bridge_json);

    let outside_main: HashSet<&str> = COMMANDS_OUTSIDE_MAIN.iter().copied().collect();

    let mut missing = Vec::new();
    for cmd in &commands {
        let expected = format!("allow-{}", command_to_allow_ident(cmd));
        // Allowed if in main.json OR in bridge.json (if listed as
        // bridge-only in COMMANDS_OUTSIDE_MAIN).
        if main_allows.contains(&expected) {
            continue;
        }
        if bridge_allows.contains(&expected) && outside_main.contains(cmd.as_str()) {
            continue;
        }
        missing.push((cmd.clone(), expected));
    }

    assert!(
        missing.is_empty(),
        "\n\n❌ Tauri runtime ACL drift (Lesson 836, 2026-09-09)!\n\
         These commands have no runtime ACL entry in capabilities/main.json:\n  - {}\n\n\
         If a command is intentionally scoped to capabilities/bridge.json \
         (the chat bridge origin), add it to COMMANDS_OUTSIDE_MAIN in this \
         test. Otherwise add `\"allow-<name>\"` to main.json's permissions.\n",
        missing
            .iter()
            .map(|(c, a)| format!("fn {} → missing {} in main.json", c, a))
            .collect::<Vec<_>>()
            .join("\n  - ")
    );

    println!(
        "\n✓ all {} #[tauri::command] functions are reachable via main.json or bridge.json",
        commands.len()
    );
}

#[test]
fn tauri_commands_are_discoverable() {
    // Sanity check: the parser must find SOME commands. If this is zero,
    // our regex broke and the other tests are useless.
    let root = project_root();
    let src_root = root.join("src-tauri/src");
    let commands = discover_tauri_commands(&src_root);
    assert!(
        commands.len() >= 10,
        "expected at least 10 #[tauri::command] functions, found {} — \
         parser is broken or src tree is empty",
        commands.len()
    );
    println!("discovered {} #[tauri::command] functions", commands.len());
}
