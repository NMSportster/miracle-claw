#!/usr/bin/env node
// scripts/sync-toolbar-module-help.mjs
//
// Lesson 1144 (2026-11-02, David): the OpenClaw chat toolbar
// (depot/openclaw-patches/dist/control-ui/mc-toolbar.js) is
// deliberately SELF-CONTAINED -- it runs inside the OpenClaw dist page
// and cannot import from MC's src/ tree. That means it needs its own
// copy of the module help content.
//
// Two copies drift. This script generates the toolbar's copy from the
// canonical src/data/{module,maic-module}-help.js so they can't.
//
// Usage:
//   node scripts/sync-toolbar-module-help.mjs          # write
//   node scripts/sync-toolbar-module-help.mjs --check  # verify only
//
// The generated block lives between the marker comments:
//   // >>> BEGIN GENERATED: MODULE-HELP >>>
//   ...
//   // <<< END GENERATED: MODULE-HELP <<<

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '..');

const CANONICAL = [
  resolve(REPO_ROOT, 'src/data/module-help.js'),
  resolve(REPO_ROOT, 'src/data/maic-module-help.js'),
];
const TOOLBAR = resolve(
  REPO_ROOT,
  'depot/openclaw-patches/dist/control-ui/mc-toolbar.js'
);

const BEGIN = '  // >>> BEGIN GENERATED: MODULE-HELP >>>';
const END = '  // <<< END GENERATED: MODULE-HELP <<<';

async function loadCanonical() {
  const merged = {};
  for (const file of CANONICAL) {
    const mod = await import(file + `?v=${Date.now()}`);
    const src = mod.MODULE_HELP || mod.MAIC_MODULE_HELP || {};
    for (const [id, help] of Object.entries(src)) merged[id] = help;
  }
  return merged;
}

/**
 * Compact the help for embedding:
 *  - keep the sections the toolbar renders
 *  - drop terminal/chat slash-command lists when empty (already empty)
 *  - keep troubleshooting (the most valuable part for a stuck user)
 */
function compact(help) {
  return {
    whoFor: help.whoFor || '',
    whyUseIt: help.whyUseIt || '',
    whatItDoes: help.whatItDoes || '',
    windowsUI: (help.windowsUI || []).map((s) => ({
      surface: s.surface || '',
      steps: (s.steps || []).map(String),
    })),
    examples: (help.examples || []).map(String),
    terminal: (help.terminal || []).map((c) => ({
      cmd: c.cmd || '',
      desc: c.desc || '',
    })),
    chat: (help.chat || []).map((c) => ({
      cmd: c.cmd || '',
      desc: c.desc || '',
    })),
    troubleshooting: (help.troubleshooting || []).map((t) => ({
      problem: t.problem || '',
      fix: t.fix || '',
    })),
  };
}

function renderBlock(helpMap) {
  const obj = {};
  for (const id of Object.keys(helpMap).sort()) {
    obj[id] = compact(helpMap[id]);
  }
  const json = JSON.stringify(obj, null, 2)
    .split('\n')
    .map((l, i) => (i === 0 ? l : '  ' + l))
    .join('\n');
  return [
    BEGIN,
    '  // GENERATED by scripts/sync-toolbar-module-help.mjs — DO NOT EDIT BY HAND.',
    '  // Source of truth: src/data/module-help.js + src/data/maic-module-help.js',
    '  // Run `node scripts/sync-toolbar-module-help.mjs` after editing those.',
    '  var TOOLBAR_MODULE_HELP = ' + json + ';',
    END,
  ].join('\n');
}

const canonical = await loadCanonical();
const block = renderBlock(canonical);
const src = await readFile(TOOLBAR, 'utf8');

const beginIdx = src.indexOf(BEGIN);
const endIdx = src.indexOf(END);
if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
  console.error(
    `ERROR: markers not found in ${TOOLBAR}.\n` +
      `Expected:\n  ${BEGIN}\n  ${END}`
  );
  process.exit(1);
}

const next =
  src.slice(0, beginIdx) + block + src.slice(endIdx + END.length);

if (process.argv.includes('--check')) {
  if (next !== src) {
    console.error(
      'FAIL: toolbar module-help block is out of date.\n' +
        'Run: node scripts/sync-toolbar-module-help.mjs'
    );
    process.exit(1);
  }
  console.log(
    `OK: toolbar module-help block is current (${Object.keys(canonical).length} modules).`
  );
} else {
  if (next !== src) {
    await writeFile(TOOLBAR, next);
    console.log(
      `Wrote ${Object.keys(canonical).length} module help entries into ${TOOLBAR}`
    );
  } else {
    console.log('Toolbar module-help block already current — no change.');
  }
}
